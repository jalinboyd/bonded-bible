/**
 * Generates SQL INSERT statements for `stories` and `events` from
 * data.js, so the ~100-story dataset the frontend already uses becomes
 * the seed data for the Supabase backend too — one source of truth,
 * no re-typing content into SQL by hand.
 *
 * Usage:
 *   node scripts/generate-seed-sql.js > backend/seed.sql
 *
 * Then run backend/schema.sql followed by backend/seed.sql in the
 * Supabase SQL editor (in that order).
 */
const path = require("path");
const { STORIES } = require(path.join(__dirname, "..", "data.js"));

function esc(str) {
  return String(str).replace(/'/g, "''");
}

/** Best-effort parse of "Book Chapter:VerseStart-VerseEnd" into parts.
 *  Falls back gracefully for chapter-only or multi-chapter references —
 *  book/chapter/verse columns are a convenience for querying, the
 *  scripture_reference text column is always the source of truth. */
function parseReference(ref) {
  const m = ref.match(/^([1-3]?\s?[A-Za-z ]+?)\s+(\d+)(?::(\d+)(?:-(\d+))?)?/);
  if (!m) return { book: null, chapter: null, verseStart: null, verseEnd: null };
  const [, book, chapter, vStart, vEnd] = m;
  return {
    book: book.trim(),
    chapter: chapter ? parseInt(chapter, 10) : null,
    verseStart: vStart ? parseInt(vStart, 10) : null,
    verseEnd: vEnd ? parseInt(vEnd, 10) : vStart ? parseInt(vStart, 10) : null,
  };
}

const lines = [];
lines.push("-- Generated by scripts/generate-seed-sql.js from data.js — do not hand-edit.");
lines.push("begin;");
lines.push("");

for (const story of STORIES) {
  lines.push(
    `insert into stories (story_key, name, category, subcategory, difficulty, description) values (` +
      `'${esc(story.key)}', '${esc(story.name)}', '${story.category}', '${esc(story.subcategory)}', ` +
      `${story.difficulty}, '${esc(story.description)}');`
  );
  for (const ev of story.events) {
    const { book, chapter, verseStart, verseEnd } = parseReference(ev.reference);
    lines.push(
      `insert into events (story_id, event_text, scripture_reference, book, chapter, verse_start, verse_end, sequence) ` +
        `select id, '${esc(ev.text)}', '${esc(ev.reference)}', ` +
        `${book ? `'${esc(book)}'` : "null"}, ${chapter ?? "null"}, ${verseStart ?? "null"}, ${verseEnd ?? "null"}, ${ev.sequence} ` +
        `from stories where story_key = '${esc(story.key)}';`
    );
  }
}

lines.push("");
lines.push("commit;");

console.log(lines.join("\n"));
